"""
UniversalSimulationEngine — Fallback for any domain without a specialist engine.

Handles: biology, economics, history, geography, law, linguistics, art,
music theory, philosophy, psychology, and any future domain the LLM detects.

Instead of pre-computing ground-truth values (which requires domain-specific
math), it maps the LLM-detected concept metadata into the closest DSL
primitives available: annotation, equation_write, algorithm_step,
procedural_sketch, and graph_function.

The detailed explanatory content is always generated by GenerativeSynthesizer
(LLM). This engine's job is to produce the correct structural skeleton so
the whiteboard renders something sensible for any topic.
"""

from __future__ import annotations

import uuid
from typing import Any

from app.domains.base import BaseSimulationEngine
from app.dsl.primitives import DSLInstruction, DSLPrimitiveType


# Cognitive structure → best-fit primitive mapping for unknown domains
_STRUCTURE_PRIMITIVE_MAP = {
    "sequential_protocol_flow": DSLPrimitiveType.ALGORITHM_STEP,
    "temporal_evolution":       DSLPrimitiveType.TRAJECTORY_DIAGRAM,
    "symbolic_balance":         DSLPrimitiveType.EQUATION_WRITE,
    "mapping_system":           DSLPrimitiveType.ANNOTATION,
    "hierarchical_transition":  DSLPrimitiveType.ANNOTATION,
}

_DEFAULT_REGION_MAP = {
    DSLPrimitiveType.ALGORITHM_STEP:   "CODE_REGION",
    DSLPrimitiveType.TRAJECTORY_DIAGRAM: "FIELD_REGION",
    DSLPrimitiveType.EQUATION_WRITE:   "EQUATION_REGION",
    DSLPrimitiveType.ANNOTATION:       "MAIN_VISUAL_REGION",
}


class UniversalSimulationEngine(BaseSimulationEngine):
    domain_name = "general"
    required_primitive_types = []
    """
    Domain-agnostic engine.  Works for any subject the LLM can classify.

    The concept_payload may contain any or all of:
      - concept       : str   — the topic name
      - domain        : str   — detected primary domain
      - subdomain     : str   — detected subdomain
      - title         : str   — display title
      - key_points    : list  — bullet facts to annotate
      - latex         : str   — equation/formula if present
      - steps         : list  — process steps (maps to algorithm_step)
      - cognitive_structure : str — from ConceptClassifier
      - visualization_type  : list — LLM-suggested vis types

    If the payload is sparse (LLM gave little metadata), we produce at
    minimum a title annotation + procedural_sketch placeholder.
    """

    def process_concept(self, concept_payload: dict[str, Any]) -> list[DSLInstruction]:
        concept = concept_payload.get("concept", "")
        title   = concept_payload.get("title", concept) or concept
        domain  = concept_payload.get("domain", "general")

        instructions: list[DSLInstruction] = []
        uid = lambda: uuid.uuid4().hex[:6]

        # ── 1. Title annotation ────────────────────────────────────
        instructions.append(DSLInstruction(
            primitive_type=DSLPrimitiveType.ANNOTATION,
            action="create",
            data={
                "annotation_id": f"title_{uid()}",
                "text": title,
                "style": "emphasis",
                "color": "#82AAFF",
            },
            region="EQUATION_REGION",
            duration_ms=700,
        ))

        # ── 2. Key-point annotations ───────────────────────────────
        key_points = concept_payload.get("key_points", [])
        for i, point in enumerate(key_points[:4]):
            instructions.append(DSLInstruction(
                primitive_type=DSLPrimitiveType.ANNOTATION,
                action="create",
                data={
                    "annotation_id": f"kp_{i}_{uid()}",
                    "text": str(point),
                    "style": "default",
                },
                region="MAIN_VISUAL_REGION",
                duration_ms=600,
                difficulty=0.4,
            ))

        # ── 3. Formula / equation ──────────────────────────────────
        latex = concept_payload.get("latex") or concept_payload.get("formula")
        if latex:
            instructions.append(DSLInstruction(
                primitive_type=DSLPrimitiveType.EQUATION_WRITE,
                action="create",
                data={
                    "equation_id": f"eq_{uid()}",
                    "latex": str(latex),
                    "total_duration_ms": 1200,
                    "metadata": {"domain": domain},
                },
                region="EQUATION_REGION",
                duration_ms=1200,
            ))

        # ── 4. Process steps → algorithm_step ─────────────────────
        steps = concept_payload.get("steps", [])
        for i, step in enumerate(steps[:5]):
            instructions.append(DSLInstruction(
                primitive_type=DSLPrimitiveType.ALGORITHM_STEP,
                action="create",
                data={
                    "step_id": f"step_{i}_{uid()}",
                    "title": f"Step {i + 1}",
                    "explanation": str(step),
                },
                region="CODE_REGION",
                duration_ms=700,
                difficulty=0.45,
            ))

        # ── 5. Graph/chart hint from visualization_type ────────────
        vis_types = concept_payload.get("visualization_type", [])
        wants_graph = any(
            kw in " ".join(vis_types).lower()
            for kw in ("graph", "chart", "curve", "plot", "function", "trend")
        )
        equation_str = concept_payload.get("graph_equation", "")
        if wants_graph and equation_str:
            instructions.append(DSLInstruction(
                primitive_type=DSLPrimitiveType.GRAPH_FUNCTION,
                action="create",
                data={"equation": equation_str},
                region="GRAPH_REGION",
                duration_ms=1000,
            ))

        # ── 6. Procedural sketch for diagrams/illustrations ────────
        wants_diagram = any(
            kw in " ".join(vis_types).lower()
            for kw in ("diagram", "sketch", "illustration", "map", "cycle",
                       "flow", "network", "layer", "structure")
        )
        shapes = concept_payload.get("sketch_shapes", [])
        if wants_diagram or shapes:
            if not shapes:
                # Generic labeled box as placeholder
                shapes = [
                    {"type": "label", "props": {
                        "text": title, "x": 0, "y": 0, "font_size": 20
                    }}
                ]
            instructions.append(DSLInstruction(
                primitive_type=DSLPrimitiveType.PROCEDURAL_SKETCH,
                action="create",
                data={
                    "sketch_id": f"sketch_{uid()}",
                    "shapes": shapes,
                },
                region="MAIN_VISUAL_REGION",
                duration_ms=800,
            ))

        # ── 7. Minimum viable output guarantee ─────────────────────
        # If nothing produced content beyond the title, add a callout.
        if len(instructions) == 1:
            instructions.append(DSLInstruction(
                primitive_type=DSLPrimitiveType.CALLOUT,
                action="create",
                data={
                    "callout_id": f"callout_{uid()}",
                    "title": domain.replace("_", " ").title(),
                    "body": f"Explaining: {concept}",
                    "style": "info",
                },
                region="MAIN_VISUAL_REGION",
                duration_ms=600,
            ))

        return instructions
