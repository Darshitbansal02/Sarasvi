def get_glyph(char: str):
    if char in VECTOR_GLYPHS:
        return VECTOR_GLYPHS[char]
    lower = char.lower()
    if lower in VECTOR_GLYPHS:
        return VECTOR_GLYPHS[lower]
    # Handle direct unicode matches for named extended entities
    replacements = {
        "ω": "omega", "φ": "phi", "ψ": "psi", "ε": "epsilon", "δ": "delta",
        "γ": "gamma", "ν": "nu", "η": "eta", "ξ": "xi", "ρ": "rho",
        "τ": "tau", "χ": "chi", "ζ": "zeta",
        # Unicode subscript digits → regular digit strokes
        "₀": "0", "₁": "1", "₂": "2", "₃": "3", "₄": "4",
        "₅": "5", "₆": "6", "₇": "7", "₈": "8", "₉": "9",
        # Unicode superscript digits → regular digit strokes
        "⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4",
        "⁵": "5", "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9",
    }
    if char in replacements and replacements[char] in VECTOR_GLYPHS:
        return VECTOR_GLYPHS[replacements[char]]
    # No vector strokes for this char — signal frontend to render as styled text
    return []
